const arb = (lang, pick) => {
  const out = {'@@locale': lang};
  for (const [key, [en, ar, placeholders]] of Object.entries(messages)) {
    out[key] = pick(en, ar);
    if (placeholders && lang === 'en') {
      out[`@${key}`] = {
        placeholders: Object.fromEntries(
          Object.entries(placeholders).map(([n, type]) => [n, {type}]),
        ),
      };
    }
  }
  return JSON.stringify(out, null, 2) + '\n';
};

